#!/usr/bin/env node
/**
 * Bundle the runtime-read content files into a generated TS module.
 *
 * On Cloudflare Workers there is no project filesystem at request time
 * (`node:fs` is an empty in-memory FS), so anything the app used to read
 * from `content/` or check in `public/` via fs must be compiled into the
 * bundle. This script snapshots:
 *   - content/reports/*.mdx (raw source + mtime) -> lib/reports/*
 *   - content/watch.md                           -> lib/watch-list.ts
 *   - the list of files under public/reports     -> app/reports/page.tsx
 *   - each report's MDX body, compiled to a JS module -> app/reports/[slug]
 *     (next-mdx-remote compiles at request time and evaluates with
 *     `new Function`, which Workers forbid; compiling here avoids eval)
 *
 * Runs automatically before `dev`, `build`, `dev:next` and `build:next`
 * (npm pre-scripts). Output is gitignored. Edit content, then rebuild.
 */
import { promises as fs } from "node:fs"
import path from "node:path"
import matter from "gray-matter"
import { compile } from "@mdx-js/mdx"
import remarkGfm from "remark-gfm"

const root = process.cwd()
const outFile = path.join(root, "lib", "generated", "content-bundle.ts")

async function readReports() {
  const dir = path.join(root, "content", "reports")
  const out = {}
  for (const f of (await fs.readdir(dir)).sort()) {
    if (!f.endsWith(".mdx")) continue
    const p = path.join(dir, f)
    const [raw, stat] = await Promise.all([fs.readFile(p, "utf-8"), fs.stat(p)])
    out[f.replace(/\.mdx$/, "")] = { raw, mtime: Math.floor(stat.mtimeMs / 1000) }
  }
  return out
}

async function listPublic(sub) {
  const base = path.join(root, "public")
  const files = []
  async function walk(dir) {
    let entries
    try {
      entries = await fs.readdir(dir, { withFileTypes: true })
    } catch {
      return
    }
    for (const e of entries) {
      const p = path.join(dir, e.name)
      if (e.isDirectory()) await walk(p)
      else files.push("/" + path.relative(base, p).split(path.sep).join("/"))
    }
  }
  await walk(path.join(base, sub))
  return files.sort()
}

async function readOptional(p) {
  try {
    return await fs.readFile(path.join(root, p), "utf-8")
  } catch {
    return null
  }
}

const reports = await readReports()
const watchMd = await readOptional("content/watch.md")
const publicFiles = await listPublic("reports")

const src = `// GENERATED by scripts/bundle-content.mjs. Do not edit; do not commit.
export const REPORT_FILES: Record<string, { raw: string; mtime: number }> = ${JSON.stringify(reports, null, 2)}

export const WATCH_MD: string | null = ${JSON.stringify(watchMd)}

export const PUBLIC_REPORT_FILES: ReadonlySet<string> = new Set(${JSON.stringify(publicFiles, null, 2)})
`

await fs.mkdir(path.dirname(outFile), { recursive: true })
await fs.writeFile(outFile, src)

// Compile each report body (frontmatter stripped) to an ES module that
// default-exports MDXContent({ components }). Same options the route used
// with MDXRemote: remark-gfm, JS expressions allowed (trusted in-repo content).
const mdxDir = path.join(root, "lib", "generated", "reports")
await fs.rm(mdxDir, { recursive: true, force: true })
await fs.mkdir(mdxDir, { recursive: true })
const slugs = Object.keys(reports)
for (const slug of slugs) {
  const { content } = matter(reports[slug].raw)
  const js = await compile(content, {
    remarkPlugins: [remarkGfm],
    outputFormat: "program",
    jsxImportSource: "react",
    development: false,
  })
  await fs.writeFile(path.join(mdxDir, `${slug}.js`), `// GENERATED from content/reports/${slug}.mdx\n${String(js)}`)
}
const idx = `// GENERATED by scripts/bundle-content.mjs. Do not edit; do not commit.
import type { ComponentType } from "react"
${slugs.map((s, i) => `// @ts-ignore generated JS module\nimport M${i} from "./reports/${s}.js"`).join("\n")}

export type MDXContentType = ComponentType<{ components?: Record<string, unknown> }>

export const REPORT_MDX: Record<string, MDXContentType> = {
${slugs.map((s, i) => `  ${JSON.stringify(s)}: M${i} as MDXContentType,`).join("\n")}
}
`
await fs.writeFile(path.join(root, "lib", "generated", "report-mdx.ts"), idx)
console.log(
  `[bundle-content] ${Object.keys(reports).length} reports, watch.md=${watchMd != null}, ${publicFiles.length} public/reports files -> ${path.relative(root, outFile)}`,
)
